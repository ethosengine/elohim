#!/usr/bin/env node
/**
 * Route-claims codegen — the single home for bundle route claims.
 *
 * Per the 2026-07-02 epr-resolution-provider design (§4/I3): bundle contentType
 * route claims (RouteClaimTemplate, pillar-epr-decomposition spec §3.1) are
 * DECLARED once in each app manifest (elohim/sdk/domains/<name>/manifest.json)
 * under the top-level `routeClaims` key, and both consumers are GENERATED here.
 *
 * Reads (top-level inline keys only — no $ref resolution):
 *   - elohim/sdk/domains/<name>/manifest.json  →  routeClaims[], ownsUniversalRoute
 *
 * Produces:
 *   - Per bundle (self-contained, no imports):
 *       lamad  → app/lamad/src/app/generated/route-claims.ts
 *       elohim → app/elohim-app/src/app/generated/route-claims.ts
 *     Emitting <PREFIX>_ROUTE_CLAIMS (readonly) + <PREFIX>_OWNS_UNIVERSAL_ROUTE.
 *   - One combined seeder file:
 *       genesis/seeder/src/generated/route-claims.ts
 *     Emitting a mutable <PREFIX>_ROUTE_CLAIMS per claim-bearing domain — the
 *     seeder builds project-epr grant objects from it (those become the doorway
 *     EprRouter's runtime claims index).
 *
 * Cross-domain gates (fail loud — the doorway rejects claim conflicts at grant
 * time; this codegen is the earlier gate):
 *   - a contentType claimed by more than one domain
 *   - more than one domain declaring ownsUniversalRoute: true
 *   - a claim-bearing domain with no registered bundle target (wiring stays conscious)
 *
 * Usage:
 *   node codegen-route-claims.mjs           # Generate all
 *   node codegen-route-claims.mjs --verify  # Check if generated files are stale
 */
import { readFile, writeFile, readdir, mkdir } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
// elohim/sdk/schemas/scripts → repo root is four levels up.
const REPO_ROOT = resolve(__dirname, '../../../../');
const DOMAINS_DIR = resolve(REPO_ROOT, 'elohim/sdk/domains');

const VERIFY = process.argv.includes('--verify');
const REGEN_CMD = 'pnpm run route-claims:codegen';

// Bundle target map (hardcoded). A claim-bearing domain with no entry here FAILS
// the run so new wiring stays conscious.
const BUNDLE_TARGETS = {
  lamad: 'app/lamad/src/app/generated/route-claims.ts',
  elohim: 'app/elohim-app/src/app/generated/route-claims.ts',
};

const SEEDER_TARGET = 'genesis/seeder/src/generated/route-claims.ts';

const INTERFACE_BLOCK = `/** Serializable claim shape (spec §3.1) — what bundle manifests DECLARE. */
export interface RouteClaimTemplate {
  contentType: string;
  template: string;
  fragments?: Record<string, string>;
}`;

// ---------------------------------------------------------------------------
// Manifest walk
// ---------------------------------------------------------------------------

async function collectDomains() {
  const entries = await readdir(DOMAINS_DIR, { withFileTypes: true });
  const domains = [];
  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    const manifestPath = resolve(DOMAINS_DIR, entry.name, 'manifest.json');
    let manifest;
    try {
      manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
    } catch {
      continue; // no manifest.json (or unreadable) → not a participating domain
    }

    const declaresClaims = Object.prototype.hasOwnProperty.call(manifest, 'routeClaims');
    const declaresOwns = Object.prototype.hasOwnProperty.call(manifest, 'ownsUniversalRoute');
    if (!declaresClaims && !declaresOwns) continue; // declares neither → skip

    const claims = manifest.routeClaims ?? [];
    if (!Array.isArray(claims)) {
      console.error(
        `FAIL: ${entry.name} manifest routeClaims must be an array (got ${typeof claims}). Fix elohim/sdk/domains/${entry.name}/manifest.json`,
      );
      process.exit(1);
    }
    const ownsUniversalRoute = manifest.ownsUniversalRoute ?? false;

    domains.push({ name: entry.name, claims, ownsUniversalRoute });
  }
  // Deterministic order so generated bytes never depend on readdir order.
  domains.sort((a, b) => a.name.localeCompare(b.name));
  return domains;
}

function validateCrossDomain(domains) {
  // (a) same contentType claimed by more than one domain
  const claimedBy = new Map(); // contentType -> domain name
  for (const domain of domains) {
    for (const claim of domain.claims) {
      const prior = claimedBy.get(claim.contentType);
      if (prior !== undefined) {
        console.error(
          `FAIL: route-claim conflict — contentType '${claim.contentType}' is claimed by more than one domain (${prior} and ${domain.name}). The doorway rejects claim conflicts at grant time; this codegen is the earlier gate.`,
        );
        process.exit(1);
      }
      claimedBy.set(claim.contentType, domain.name);
    }
  }

  // (b) more than one domain declaring ownsUniversalRoute: true
  const universalOwners = domains.filter((d) => d.ownsUniversalRoute).map((d) => d.name);
  if (universalOwners.length > 1) {
    console.error(
      `FAIL: more than one domain declares ownsUniversalRoute: true (${universalOwners.join(', ')}). At most one bundle may own the universal /epr route.`,
    );
    process.exit(1);
  }

  // (c) a claim-bearing / route-owning domain with no registered bundle target
  for (const domain of domains) {
    if (!BUNDLE_TARGETS[domain.name]) {
      console.error(
        `FAIL: domain '${domain.name}' declares route claims but has no registered bundle target. Add it to BUNDLE_TARGETS in codegen-route-claims.mjs so wiring stays conscious.`,
      );
      process.exit(1);
    }
  }
}

// ---------------------------------------------------------------------------
// TypeScript emitters (bytes must be a prettier fixed point — single quotes,
// es5 trailing commas, 100-char width; no post-hoc prettier --write)
// ---------------------------------------------------------------------------

const IDENT_RE = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

function emitString(value) {
  return `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

function emitKey(key) {
  return IDENT_RE.test(key) ? key : emitString(key);
}

function emitClaim(claim) {
  const parts = [
    `contentType: ${emitString(claim.contentType)}`,
    `template: ${emitString(claim.template)}`,
  ];
  if (claim.fragments && Object.keys(claim.fragments).length > 0) {
    const frags = Object.entries(claim.fragments)
      .map(([k, v]) => `${emitKey(k)}: ${emitString(v)}`)
      .join(', ');
    parts.push(`fragments: { ${frags} }`);
  }
  return `{ ${parts.join(', ')} }`;
}

function emitClaimsArray(claims) {
  if (claims.length === 0) return '[]';
  const lines = claims.map((c) => `  ${emitClaim(c)},`).join('\n');
  return `[\n${lines}\n]`;
}

function bundleHeader(name) {
  return `// AUTO-GENERATED from app manifest: elohim/sdk/domains/${name}/manifest.json
// DO NOT EDIT — regenerate with: ${REGEN_CMD}`;
}

function emitBundleClaimsArray(domains) {
  const claimBearing = domains.filter((d) => d.claims.length > 0);
  if (claimBearing.length === 0) return '[]';
  const bundleLines = claimBearing
    .map((d) => {
      const claimsStr = emitClaimsArray(d.claims).replace(/\n/g, '\n    ');
      return `  {\n    bundle: ${emitString(d.name)},\n    claims: ${claimsStr},\n  }`;
    })
    .join(',\n');
  return `[\n${bundleLines},\n]`;
}

function generateBundleFile(domain, domains) {
  const prefix = domain.name.toUpperCase();
  const universal = domain.ownsUniversalRoute
    ? `

/** Every declaring bundle's claims — the universal-route owner mints cross-bundle lenses from these. */
export const BUNDLE_ROUTE_CLAIMS: readonly {
  bundle: string;
  claims: readonly RouteClaimTemplate[];
}[] = ${emitBundleClaimsArray(domains)};
`
    : '';
  return `${bundleHeader(domain.name)}

${INTERFACE_BLOCK}

/** ${domain.name}'s DECLARED route claims (manifest \`routeClaims\`). */
export const ${prefix}_ROUTE_CLAIMS: readonly RouteClaimTemplate[] = ${emitClaimsArray(domain.claims)};

/** Whether this bundle owns the universal /epr route (manifest \`ownsUniversalRoute\`). */
export const ${prefix}_OWNS_UNIVERSAL_ROUTE = ${domain.ownsUniversalRoute};${universal}\n`;
}

function generateSeederFile(domains) {
  // The seeder mints project-epr grant claims; a bundle with no type-claims (the
  // shell) produces no grant, so only claim-bearing domains appear here.
  const claimBearing = domains.filter((d) => d.claims.length > 0);
  const blocks = [
    `// AUTO-GENERATED from app manifests: elohim/sdk/domains/*/manifest.json
// DO NOT EDIT — regenerate with: ${REGEN_CMD}`,
    '',
    INTERFACE_BLOCK,
  ];
  for (const domain of claimBearing) {
    const prefix = domain.name.toUpperCase();
    blocks.push('');
    blocks.push(`/** ${domain.name}'s DECLARED route claims (manifest \`routeClaims\`). */`);
    blocks.push(`export const ${prefix}_ROUTE_CLAIMS: RouteClaimTemplate[] = ${emitClaimsArray(domain.claims)};`);
  }
  return blocks.join('\n') + '\n';
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

async function main() {
  const domains = await collectDomains();
  validateCrossDomain(domains);

  const outputs = new Map(); // repo-relative path -> content
  for (const domain of domains) {
    outputs.set(BUNDLE_TARGETS[domain.name], generateBundleFile(domain, domains));
  }
  outputs.set(SEEDER_TARGET, generateSeederFile(domains));

  if (VERIFY) {
    let stale = false;
    for (const [rel, content] of outputs) {
      const abs = resolve(REPO_ROOT, rel);
      let existing;
      try {
        existing = await readFile(abs, 'utf8');
      } catch {
        console.error(`FAIL: ${rel} is missing. Run: ${REGEN_CMD}`);
        stale = true;
        continue;
      }
      if (existing !== content) {
        console.error(`FAIL: ${rel} is stale. Run: ${REGEN_CMD}`);
        stale = true;
      }
    }
    if (stale) process.exit(1);
    console.log('Route-claims codegen is up to date.');
    return;
  }

  for (const [rel, content] of outputs) {
    const abs = resolve(REPO_ROOT, rel);
    await mkdir(dirname(abs), { recursive: true });
    await writeFile(abs, content);
    console.log(`Generated: ${rel}`);
  }
  console.log(`\nRoute-claims codegen complete: ${outputs.size} files`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
