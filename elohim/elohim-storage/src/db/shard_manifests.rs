//! Shard manifest CRUD operations using Diesel.
//!
//! One row per `(content_id, h_app_id)` projects the DNA `ShardManifest` shape: the
//! payload's byte CID and length, the profile it was minted under (`profile_json` =
//! `{chunker, erasure}`), its FastCDC chunks and, when erasure-coded, its stripes. Every
//! reader uses the recorded parameters, never this node's configuration. Per-peer local
//! state (Category C), not DHT-notarized.

use diesel::prelude::*;
use elohim_epr::address::ByteCid;
use serde::{Deserialize, Serialize};

use super::diesel_schema::shard_manifests;
use super::models::{NewShardManifest, ShardManifestRow};
use crate::blob_store::BlobStore;
use crate::sharding::{ChunkerDecl, ErasureDecl, ShardEncoder, ShardError, ShardManifest};
use crate::StorageError;

impl From<ShardError> for StorageError {
    fn from(error: ShardError) -> Self {
        StorageError::Validation(error.to_string())
    }
}

/// The parameters a manifest was minted under, as `profile_json` stores them.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ManifestProfile {
    pub chunker: ChunkerDecl,
    pub erasure: ErasureDecl,
}

/// Persist a manifest that was already generated by a byte-handling path.
///
/// Callers retain their honest scope: distribution supplies the application content id
/// it is placing, while bare blob ingress supplies `blob:{cid}` as a local projection key.
/// This keeps the shard-to-blob relation available to the custody-facing fold without
/// asserting a new DHT fact or fabricating an application content record.
pub fn record_generated_manifest(
    conn: &mut SqliteConnection,
    content_id: &str,
    h_app_id: &str,
    manifest: &ShardManifest,
) -> Result<ShardManifestRow, StorageError> {
    let blob_cid = manifest.blob_cid.to_string();
    let profile_json = serde_json::to_string(&ManifestProfile {
        chunker: manifest.chunker,
        erasure: manifest.erasure.clone(),
    })?;
    let chunks_json = serde_json::to_string(&manifest.chunks)?;
    let stripes_json = serde_json::to_string(&manifest.stripes)?;
    let byte_len = i64::try_from(manifest.byte_len)
        .map_err(|_| StorageError::InvalidInput(format!("byte_len {}", manifest.byte_len)))?;
    let new_manifest = NewShardManifest {
        content_id,
        h_app_id,
        blob_cid: &blob_cid,
        byte_len,
        mime_type: &manifest.mime_type,
        profile_json: &profile_json,
        chunks_json: &chunks_json,
        stripes_json: &stripes_json,
        reach: &manifest.reach,
        author_id: manifest.author_id.as_deref(),
        created_at: &manifest.created_at,
        verified_at: manifest.verified_at.as_deref(),
    };
    upsert_manifest(conn, &new_manifest)
}

/// Mint a manifest for `data` and upsert it for `(content_id, h_app_id)`.
///
/// Single source of truth for "blob bytes → persisted shard manifest": the
/// `POST /db/content` create path and the startup backfill both converge here.
/// `content_format` becomes the manifest mime type; `reach` is recorded verbatim.
pub fn record_manifest_from_bytes(
    conn: &mut SqliteConnection,
    content_id: &str,
    h_app_id: &str,
    data: &[u8],
    content_format: &str,
    reach: &str,
) -> Result<ShardManifestRow, StorageError> {
    let encoder = ShardEncoder::new(crate::sharding::ShardConfig::default());
    let manifest = encoder.create_manifest(data, content_format, reach)?;
    record_generated_manifest(conn, content_id, h_app_id, &manifest)
}

/// Shape-aware entry point every manifest PRODUCER (`POST /db/content`,
/// `/db/content/bulk`, `services::shard_manifest_backfill`) calls.
///
/// A manifest already known for `blob_cid` (any `(content_id, h_app_id)` row keyed to
/// the same byte CID names the same chunks and stripes, content-addressed) is reused for
/// the new projection key without reading a byte; otherwise the payload is read
/// (verified) and a fresh manifest minted.
pub async fn record_manifest_for_blob(
    conn: &mut SqliteConnection,
    blob_store: &BlobStore,
    content_id: &str,
    h_app_id: &str,
    blob_cid: &ByteCid,
    content_format: &str,
    reach: &str,
) -> Result<ShardManifestRow, StorageError> {
    if let Some(existing) = resolve_manifest_by_cid(conn, blob_cid) {
        return record_generated_manifest(conn, content_id, h_app_id, &existing);
    }
    let data = read_blob_bytes_for_manifest(conn, blob_store, blob_cid).await?;
    record_manifest_from_bytes(conn, content_id, h_app_id, &data, content_format, reach)
}

/// The payload's bytes, for producers that need them (e.g. `p2p::distribute_shards`).
///
/// The whole payload is read from the store first (verified against `blob_cid`). When it
/// is absent and a known manifest declares stripes, each stripe is reassembled from the
/// shards held locally under their own CIDs (any `data` of `data + parity` suffice);
/// [`ShardEncoder::reconstruct`] checks every shard and the whole against its CID. With
/// no payload and no striped manifest there is nothing to reassemble from: `NotFound`.
pub async fn read_blob_bytes_for_manifest(
    conn: &mut SqliteConnection,
    blob_store: &BlobStore,
    blob_cid: &ByteCid,
) -> Result<Vec<u8>, StorageError> {
    match blob_store.get(blob_cid).await {
        Ok(bytes) => return Ok(bytes.to_vec()),
        Err(StorageError::HashMismatch { .. }) => {
            // Quarantined by the store; fall through to the shards, never serve it.
        }
        Err(_) => {}
    }

    let manifest = resolve_manifest_by_cid(conn, blob_cid)
        .ok_or_else(|| StorageError::NotFound(blob_cid.to_string()))?;
    if manifest.stripes.is_empty() {
        return Err(StorageError::NotFound(blob_cid.to_string()));
    }

    let mut stripes = Vec::with_capacity(manifest.stripes.len());
    for stripe in &manifest.stripes {
        let mut shards = Vec::with_capacity(stripe.shards.len());
        for shard in &stripe.shards {
            // A missing shard is a per-slot `None`: parity exists to cover it.
            shards.push(blob_store.get(&shard.cid).await.ok().map(|b| b.to_vec()));
        }
        stripes.push(shards);
    }
    Ok(ShardEncoder::reconstruct(&manifest, &stripes)?)
}

pub fn upsert_manifest(
    conn: &mut SqliteConnection,
    manifest: &NewShardManifest,
) -> Result<ShardManifestRow, StorageError> {
    // Q11 atomic timing budget: the durable write + read-back, the whole
    // "manifest persist" atom every generation/receipt path shares.
    let manifest_persist_started = std::time::Instant::now();
    let result: Result<ShardManifestRow, StorageError> = (|| {
        diesel::replace_into(shard_manifests::table)
            .values(manifest)
            .execute(conn)?;

        shard_manifests::table
            .filter(shard_manifests::content_id.eq(manifest.content_id))
            .filter(shard_manifests::h_app_id.eq(manifest.h_app_id))
            .first(conn)
            .map_err(StorageError::from)
    })();
    crate::metrics::observe_atom_duration(
        crate::metrics::ConvergenceAtom::ManifestPersist,
        manifest_persist_started.elapsed(),
    );
    result
}

/// Test fixture: a manifest row that declares only `blob_cid` and `byte_len`, for SQL
/// readers that never hydrate it (size and reach lookups). Its profile is the epoch-0
/// default and it lists no units, so [`hydrate_manifest`] refuses it.
#[cfg(test)]
pub(crate) fn insert_declared_row(
    conn: &mut SqliteConnection,
    content_id: &str,
    h_app_id: &str,
    blob_cid: &str,
    byte_len: i64,
) -> ShardManifestRow {
    let profile = ManifestProfile {
        chunker: ChunkerDecl::of(elohim_epr::profile::BYTE_PROFILE_0.chunker),
        erasure: ErasureDecl::of(elohim_epr::profile::Erasure::None),
    };
    let profile_json = serde_json::to_string(&profile).expect("profile json");
    upsert_manifest(
        conn,
        &NewShardManifest {
            content_id,
            h_app_id,
            blob_cid,
            byte_len,
            mime_type: "application/octet-stream",
            profile_json: &profile_json,
            chunks_json: "[]",
            stripes_json: "[]",
            reach: "commons",
            author_id: None,
            created_at: "2026-11-05T00:00:00Z",
            verified_at: None,
        },
    )
    .expect("insert declared manifest row")
}

/// Test fixture: an unstriped manifest row whose custody units are the given
/// chunks, each named by its byte CID (`units` entries that parse as byte CIDs are
/// used as-is; any other label names the byte CID of its own bytes, its length the
/// label's). The row hydrates; `blob_cid` is declared, not recomputed from the units.
#[cfg(test)]
pub(crate) fn insert_unit_manifest(
    conn: &mut SqliteConnection,
    content_id: &str,
    h_app_id: &str,
    blob_cid: &str,
    units: &[&str],
) -> ShardManifestRow {
    let chunks: Vec<crate::blob_store::ChunkRef> = units
        .iter()
        .map(|label| crate::blob_store::ChunkRef {
            cid: ByteCid::parse(label)
                .unwrap_or_else(|_| elohim_epr::address::compute_bytes_cid(label.as_bytes())),
            len: label.len() as u32,
        })
        .collect();
    let byte_len: i64 = chunks.iter().map(|c| i64::from(c.len)).sum();
    let profile = ManifestProfile {
        chunker: ChunkerDecl::of(elohim_epr::profile::BYTE_PROFILE_0.chunker),
        erasure: ErasureDecl::of(elohim_epr::profile::Erasure::None),
    };
    let profile_json = serde_json::to_string(&profile).expect("profile json");
    let chunks_json = serde_json::to_string(&chunks).expect("chunks json");
    upsert_manifest(
        conn,
        &NewShardManifest {
            content_id,
            h_app_id,
            blob_cid,
            byte_len,
            mime_type: "html5-app",
            profile_json: &profile_json,
            chunks_json: &chunks_json,
            stripes_json: "[]",
            reach: "commons",
            author_id: None,
            created_at: "2026-11-05T00:00:00Z",
            verified_at: None,
        },
    )
    .expect("insert unit manifest")
}

/// The custody unit a test fixture label names (see [`insert_unit_manifest`]).
#[cfg(test)]
pub(crate) fn fixture_unit(label: &str) -> String {
    ByteCid::parse(label)
        .unwrap_or_else(|_| elohim_epr::address::compute_bytes_cid(label.as_bytes()))
        .to_string()
}

pub fn get_manifest(
    conn: &mut SqliteConnection,
    h_app_id: &str,
    content_id: &str,
) -> Result<Option<ShardManifestRow>, StorageError> {
    shard_manifests::table
        .filter(shard_manifests::content_id.eq(content_id))
        .filter(shard_manifests::h_app_id.eq(h_app_id))
        .first(conn)
        .optional()
        .map_err(StorageError::from)
}

/// The durable manifest projection for a payload's byte CID.
///
/// Rows are keyed by `(content_id, h_app_id)` — ingest files them under `blob:{cid}`,
/// distribution under the application content id — and every row for one CID names the
/// same chunks and stripes. `created_at` ordering makes the pick stable.
pub fn get_manifest_by_blob_cid(
    conn: &mut SqliteConnection,
    blob_cid: &ByteCid,
) -> Result<Option<ShardManifestRow>, StorageError> {
    shard_manifests::table
        .filter(shard_manifests::blob_cid.eq(blob_cid.to_string()))
        .order(shard_manifests::created_at.desc())
        .first(conn)
        .optional()
        .map_err(StorageError::from)
}

/// Rehydrate the [`ShardManifest`] from its durable row. Every CID is admitted by full
/// decode (serde), and the result is validated ([`ShardManifest::validate`]) before it is
/// returned: a row that does not describe a consistent manifest is refused, never used.
pub fn hydrate_manifest(row: &ShardManifestRow) -> Result<ShardManifest, StorageError> {
    let blob_cid = ByteCid::parse(&row.blob_cid)
        .map_err(|e| StorageError::Validation(format!("shard manifest blob_cid: {e}")))?;
    let profile: ManifestProfile = serde_json::from_str(&row.profile_json)?;
    let manifest = ShardManifest {
        blob_cid,
        byte_len: u64::try_from(row.byte_len)
            .map_err(|_| StorageError::Validation(format!("byte_len {}", row.byte_len)))?,
        mime_type: row.mime_type.clone(),
        chunker: profile.chunker,
        chunks: serde_json::from_str(&row.chunks_json)?,
        erasure: profile.erasure,
        stripes: serde_json::from_str(&row.stripes_json)?,
        reach: row.reach.clone(),
        author_id: row.author_id.clone(),
        created_at: row.created_at.clone(),
        verified_at: row.verified_at.clone(),
    };
    manifest.validate()?;
    Ok(manifest)
}

/// The custody units a manifest row names (shard CIDs when striped, else chunk CIDs), as
/// CID text for joins against `shard_locations.shard_cid`. A row that does not hydrate
/// names nothing (logged): it cannot protect or locate a unit it does not describe.
pub fn custody_unit_cids(row: &ShardManifestRow) -> Vec<String> {
    match hydrate_manifest(row) {
        Ok(manifest) => manifest
            .custody_units()
            .iter()
            .map(ToString::to_string)
            .collect(),
        Err(e) => {
            tracing::warn!(
                content_id = %row.content_id,
                error = %e,
                "shard manifest row does not hydrate; it names no custody units"
            );
            Vec::new()
        }
    }
}

/// Resolve + hydrate a shard manifest for a byte CID from the durable projection. Errors
/// are logged and folded to `None`: a manifest miss is a normal "I don't have this".
pub fn resolve_manifest_by_cid(
    conn: &mut SqliteConnection,
    blob_cid: &ByteCid,
) -> Option<ShardManifest> {
    let row = get_manifest_by_blob_cid(conn, blob_cid)
        .map_err(|e| tracing::warn!(cid = %blob_cid, error = %e, "shard manifest lookup failed"))
        .ok()
        .flatten()?;
    hydrate_manifest(&row)
        .map_err(|e| tracing::warn!(cid = %blob_cid, error = %e, "shard manifest hydration failed"))
        .ok()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::sharding::ShardConfig;
    use crate::test_util::test_pool;
    use elohim_epr::address::compute_bytes_cid;

    fn rs_encoder() -> ShardEncoder {
        // Erasure-code everything: the RS band without a 64 MiB fixture. Readers use the
        // parameters the manifest records, so the default-config reader still applies.
        ShardEncoder::new(ShardConfig {
            rs_threshold: 0,
            ..ShardConfig::default()
        })
    }

    #[test]
    fn hydrate_round_trips_every_declared_field() {
        let pool = test_pool();
        let mut conn = pool.get().expect("conn");
        let data: Vec<u8> = (0..10_000u32).map(|i| (i % 251) as u8).collect();
        let (manifest, _) = rs_encoder()
            .encode(&data, "application/octet-stream", "commons")
            .expect("encode");
        record_generated_manifest(&mut conn, "c-1", "lamad", &manifest).expect("persist");

        let row = get_manifest(&mut conn, "lamad", "c-1")
            .unwrap()
            .expect("row");
        assert_eq!(row.blob_cid, compute_bytes_cid(&data).to_string());
        assert_eq!(hydrate_manifest(&row).expect("hydrate"), manifest);
    }

    #[test]
    fn hydrate_refuses_a_row_whose_cid_is_not_a_byte_cid() {
        let pool = test_pool();
        let mut conn = pool.get().expect("conn");
        let (manifest, _) = ShardEncoder::new(ShardConfig::default())
            .encode(b"abc", "text/plain", "commons")
            .expect("encode");
        record_generated_manifest(&mut conn, "c-2", "lamad", &manifest).expect("persist");
        let mut row = get_manifest(&mut conn, "lamad", "c-2")
            .unwrap()
            .expect("row");
        // The same bytes under the sha2-256 raw profile: a CID, but not a byte CID.
        row.blob_cid = elohim_epr::address::compute_raw_sha2_cid(b"abc").to_string();
        assert!(hydrate_manifest(&row).is_err());
    }

    /// Rows are addressed by byte CID, not by the caller's projection id.
    #[test]
    fn resolve_manifest_by_cid_finds_persisted_manifest_and_none_when_absent() {
        let pool = test_pool();
        let mut conn = pool.get().expect("conn");
        let (manifest, _) = ShardEncoder::new(ShardConfig::default())
            .encode(b"hello world", "text/plain", "commons")
            .expect("encode");
        record_generated_manifest(
            &mut conn,
            &format!("blob:{}", manifest.blob_cid),
            "lamad",
            &manifest,
        )
        .expect("persist");

        let resolved = resolve_manifest_by_cid(&mut conn, &manifest.blob_cid).expect("resolves");
        assert_eq!(resolved, manifest);
        assert!(resolve_manifest_by_cid(&mut conn, &compute_bytes_cid(b"abc")).is_none());
    }

    /// A later producer for a different projection key reuses the known manifest without
    /// reading a byte (the payload is not even held here).
    #[tokio::test]
    async fn record_manifest_for_blob_reuses_known_manifest() {
        let pool = test_pool();
        let mut conn = pool.get().expect("conn");
        let blob_store = BlobStore::new_memory();
        let data = b"<html>landing</html>".to_vec();
        let (manifest, _) = ShardEncoder::new(ShardConfig::default())
            .encode(&data, "html5-app", "commons")
            .expect("encode");
        record_generated_manifest(
            &mut conn,
            &format!("blob:{}", manifest.blob_cid),
            "lamad",
            &manifest,
        )
        .expect("seed");

        let row = record_manifest_for_blob(
            &mut conn,
            &blob_store,
            "elohim-host-landing",
            "lamad",
            &manifest.blob_cid,
            "html5-app",
            "commons",
        )
        .await
        .expect("manifest reused");
        assert_eq!(row.content_id, "elohim-host-landing");
        assert_eq!(hydrate_manifest(&row).unwrap().chunks, manifest.chunks);
    }

    #[tokio::test]
    async fn record_manifest_for_blob_derives_from_bytes_when_no_manifest_known() {
        let pool = test_pool();
        let mut conn = pool.get().expect("conn");
        let blob_store = BlobStore::new_memory();
        let stored = blob_store
            .store(b"<html>small composite blob</html>")
            .await
            .expect("store");

        let row = record_manifest_for_blob(
            &mut conn,
            &blob_store,
            "small-doc",
            "lamad",
            &stored.cid,
            "html5-app",
            "commons",
        )
        .await
        .expect("manifest derived from bytes");
        let manifest = hydrate_manifest(&row).unwrap();
        assert_eq!(manifest.blob_cid, stored.cid);
        assert!(manifest.stripes.is_empty());
        assert_eq!(
            manifest.chunks.iter().map(|c| c.cid).collect::<Vec<_>>(),
            stored.chunks.iter().map(|c| c.cid).collect::<Vec<_>>()
        );
    }

    async fn seed_striped(
        blob_store: &BlobStore,
        conn: &mut SqliteConnection,
        absent: usize,
    ) -> (ShardManifest, Vec<u8>) {
        let data: Vec<u8> = (0..1000u32).map(|i| (i % 256) as u8).collect();
        let (manifest, shards) = rs_encoder()
            .encode(&data, "application/octet-stream", "commons")
            .expect("encode");
        assert_eq!(manifest.stripes.len(), 1);
        for shard in shards[0].iter().skip(absent) {
            blob_store.store(shard).await.expect("store shard");
        }
        record_generated_manifest(
            conn,
            &format!("blob:{}", manifest.blob_cid),
            "lamad",
            &manifest,
        )
        .expect("seed manifest");
        (manifest, data)
    }

    /// The payload is absent; 2 of 7 shards are missing and parity covers them.
    #[tokio::test]
    async fn read_blob_bytes_reassembles_within_rs_parity() {
        let pool = test_pool();
        let mut conn = pool.get().expect("conn");
        let blob_store = BlobStore::new_memory();
        let (manifest, data) = seed_striped(&blob_store, &mut conn, 2).await;

        let bytes = read_blob_bytes_for_manifest(&mut conn, &blob_store, &manifest.blob_cid)
            .await
            .expect("parity covers the missing shards");
        assert_eq!(bytes, data);
    }

    /// More shards absent than parity allows: an honest error, never invented bytes.
    #[tokio::test]
    async fn read_blob_bytes_errors_when_missing_exceeds_rs_parity() {
        let pool = test_pool();
        let mut conn = pool.get().expect("conn");
        let blob_store = BlobStore::new_memory();
        let (manifest, _) = seed_striped(&blob_store, &mut conn, 4).await;

        match read_blob_bytes_for_manifest(&mut conn, &blob_store, &manifest.blob_cid).await {
            Err(StorageError::Validation(msg)) => {
                assert!(msg.contains("need 4") && msg.contains("have 3"), "{msg}")
            }
            other => panic!("expected the shortfall named, got {other:?}"),
        }
    }

    #[tokio::test]
    async fn read_blob_bytes_errors_when_truly_absent() {
        let pool = test_pool();
        let mut conn = pool.get().expect("conn");
        let blob_store = BlobStore::new_memory();
        let result =
            read_blob_bytes_for_manifest(&mut conn, &blob_store, &compute_bytes_cid(b"never"))
                .await;
        assert!(matches!(result, Err(StorageError::NotFound(_))));
    }
}
