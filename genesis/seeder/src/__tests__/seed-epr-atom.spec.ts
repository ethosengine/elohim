describe('buildLandingAtomGraph', () => {
  it('mints the five-atom family in dependency order', async () => {
    const graph = await buildLandingAtomGraph();
    expect(graph.atoms.map((a) => a.schemaKey)).toEqual([
      SCHEMA_ATOM_KEY,
      GOVERNANCE_ATOM_KEY,
      STEWARDSHIP_CLAIM_KEY,
      CUSTODY_CLAIM_KEY,
      SCHEMA_KEY,
    ]);
  });

  it('is deterministic — re-running mints identical CIDs (content-addressed idempotency)', async () => {
    const a = await buildLandingAtomGraph();
    const b = await buildLandingAtomGraph();
    expect(b.atoms.map((x) => x.cid.toString())).toEqual(a.atoms.map((x) => x.cid.toString()));
  });

  it("every atom's declared CID is the hash of its own canonical bytes", async () => {
    // The storage layer derives the CID itself and rejects a mismatch. Prove
    // the declared envelope.cid is self-consistent before it ever ships.
    const graph = await buildLandingAtomGraph();
    for (const atom of graph.atoms) {
      const env = atom.body.envelope as { cid: string };
      expect(env.cid).toBe(atom.cid.toString());
      expect(atom.cid.code).toBe(DAG_CBOR_CODEC);
    }
  });

  it('points the landing governance leg at the REAL governance atom, not a literal hash', async () => {
    const graph = await buildLandingAtomGraph();
    const governance = graph.atoms.find((a) => a.schemaKey === GOVERNANCE_ATOM_KEY);
    const env = graph.landing.body.envelope as { coupling: Record<string, string | null> };
    expect(governance).toBeDefined();
    expect(env.coupling.governance).toBe(governance!.cid.toString());

    // Regression guard: the old seeder used sha256("elohim-host-governance-v1")
    // as the governance leg — a CID with nothing on the other end.
    const literal = await sha256.digest(new TextEncoder().encode('elohim-host-governance-v1'));
    const sentinel = CID.create(1, DAG_CBOR_CODEC, literal).toString();
    expect(env.coupling.governance).not.toBe(sentinel);
    for (const atom of graph.atoms) {
      const e = atom.body.envelope as {
        coupling: Record<string, string | null>;
        schemaRef: string;
        claims: string[];
      };
      expect(Object.values(e.coupling)).not.toContain(sentinel);
      expect(e.schemaRef).not.toBe(sentinel);
      expect(e.claims).not.toContain(sentinel);
    }
  });

  it('carries real claims — the stewardship and custody atoms it actually minted', async () => {
    const graph = await buildLandingAtomGraph();
    const stewardship = graph.atoms.find((a) => a.schemaKey === STEWARDSHIP_CLAIM_KEY)!;
    const custody = graph.atoms.find((a) => a.schemaKey === CUSTODY_CLAIM_KEY)!;
    const env = graph.landing.body.envelope as { claims: string[] };
    expect(env.claims).toEqual([stewardship.cid.toString(), custody.cid.toString()]);
    expect(env.claims.length).toBeGreaterThan(0);
  });

  it('satisfies every kind-required coupling leg (EprKind::required_coupling)', async () => {
    const graph = await buildLandingAtomGraph();
    for (const atom of graph.atoms) {
      const env = atom.body.envelope as { coupling: Record<string, string | null>; kind: string };
      if (env.kind === 'Manifest') {
        // Manifest requires Governance.
        expect(env.coupling.governance, `${atom.schemaKey} governance leg`).toBeTruthy();
      } else if (env.kind === 'Claim') {
        // Claim requires Knowledge.
        expect(env.coupling.knowledge, `${atom.schemaKey} knowledge leg`).toBeTruthy();
      }
    }
  });

  it('anchors the knowledge legs on the seeded content rows own anchor CIDs', async () => {
    const graph = await buildLandingAtomGraph();
    // deriveContentAnchor emits CIDv1(raw, sha2-256); the raw multicodec is 0x55.
    expect(CID.parse(graph.anchors.landingAnchor).code).toBe(0x55);
    expect(CID.parse(graph.anchors.manifestoAnchor).code).toBe(0x55);
    const env = graph.landing.body.envelope as { coupling: Record<string, string | null> };
    expect(env.coupling.knowledge).toBe(graph.anchors.landingAnchor);
    // No value leg is fabricated — Manifest does not require one.
    expect(env.coupling.value).toBeNull();
  });

  it('carries the governance state document verbatim as the governance payload', async () => {
    const graph = await buildLandingAtomGraph();
    const governance = graph.atoms.find((a) => a.schemaKey === GOVERNANCE_ATOM_KEY)!;
    const payloadHex = (governance.body as { payload: string }).payload;
    const decoded = JSON.parse(Buffer.from(payloadHex, 'hex').toString('utf-8'));
    expect(decoded.entityId).toBe('elohim-host-landing');
    expect(decoded.entityType).toBe('content');
    // Honest scoping: no invented council ratified the landing surface.
    expect(decoded.status).not.toBe('constitutional');
    expect(decoded.reviews).toEqual([]);
  });
});

