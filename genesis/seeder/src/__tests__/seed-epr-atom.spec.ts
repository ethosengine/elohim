describe('landing backing facts', () => {
  it('stewardship comes from the content own authored declaration', () => {
    const facts = landingStewardshipFacts();
    expect(facts.contentId).toBe('elohim-host-landing');
    expect(facts.provenance).toBe('authored');
    expect(facts.stewards).toEqual([
      { presenceId: 'matthew-dowell', ratio: 1, contributionType: 'original_creator' },
    ]);
  });

  it('custody names the ssr-server self-custody pledge seed-commitments seeds', () => {
    const facts = landingCustodyFacts();
    expect(facts).toMatchObject({
      action: 'custody-blob',
      contentId: 'elohim-host-landing',
      artifactRole: 'ssr-server',
      selfCustody: true,
    });
    // The deploy-time blob hash is deliberately absent — binding it would move
    // the claim CID on every SSR bundle rebuild.
    expect(JSON.stringify(facts)).not.toContain('sha256-');
  });
});
